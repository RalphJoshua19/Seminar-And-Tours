// Independent State Counters
let currentSeminarIndex = 0;
let currentCertIndex = 0;
let currentProofImageIndex = 0;

// Helper: Triggers entrance slide animation for elements
function triggerSlideAnimation(element, direction) {
  element.classList.remove('slide-in-next', 'slide-in-prev');
  void element.offsetWidth; // Force CSS Reflow
  element.classList.add(direction > 0 ? 'slide-in-next' : 'slide-in-prev');
}

// --- 1. SEMINARS & WEBINARS SECTION ---
function updateSeminarSection() {
  const current = seminarsData[currentSeminarIndex];

  document.getElementById('sem-date').innerText = current.date;
  document.getElementById('sem-hours').innerText = current.hours;
  document.getElementById('sem-issuer').innerText = current.issuer;
  document.getElementById('sem-title').innerText = current.title;
  document.getElementById('sem-desc').innerText = current.desc;

  const listContainer = document.getElementById('sem-learnings');
  listContainer.innerHTML = '';
  current.learnings.forEach(item => {
    const li = document.createElement('li');
    li.innerHTML = item;
    listContainer.appendChild(li);
  });

  const pageText = `${String(currentSeminarIndex + 1).padStart(2, '0')} / ${String(seminarsData.length).padStart(2, '0')}`;
  document.getElementById('page-indicator').innerText = pageText;

  document.getElementById('prev-btn').disabled = currentSeminarIndex === 0;
  document.getElementById('next-btn').disabled = currentSeminarIndex === seminarsData.length - 1;
}

function changePage(direction) {
  const targetIndex = currentSeminarIndex + direction;
  if (targetIndex >= 0 && targetIndex < seminarsData.length) {
    currentSeminarIndex = targetIndex;
    const cardElement = document.getElementById('seminar-card');
    triggerSlideAnimation(cardElement, direction);
    updateSeminarSection();
  }
}

// --- 2. CERTIFICATES SECTION ---
function updateCertSection() {
  const current = seminarsData[currentCertIndex];
  const certFrame = document.getElementById('cert-frame');

  if (current.certPdf.toLowerCase().endsWith('.jpg') || current.certPdf.toLowerCase().endsWith('.jpeg') || current.certPdf.toLowerCase().endsWith('.png')) {
    certFrame.innerHTML = `<img src="${current.certPdf}" alt="${current.title}" class="cert-img-display">`;
  } else {
    const encodedPdfPath = encodeURIComponent(current.certPdf);
    certFrame.innerHTML = `<iframe id="cert-pdf-display" class="cert-pdf" src="${encodedPdfPath}#toolbar=0&navpanes=0&scrollbar=0&view=FitH" type="application/pdf"></iframe>`;
  }

  const pageText = `${String(currentCertIndex + 1).padStart(2, '0')} / ${String(seminarsData.length).padStart(2, '0')}`;
  document.getElementById('cert-page-indicator').innerText = pageText;

  document.getElementById('cert-prev-btn').disabled = currentCertIndex === 0;
  document.getElementById('cert-next-btn').disabled = currentCertIndex === seminarsData.length - 1;
}

function changeCertPage(direction) {
  const targetIndex = currentCertIndex + direction;
  if (targetIndex >= 0 && targetIndex < seminarsData.length) {
    currentCertIndex = targetIndex;
    const frameElement = document.getElementById('cert-frame');
    triggerSlideAnimation(frameElement, direction);
    updateCertSection();
  }
}

// --- 3. BADGES CAROUSEL ---
let currentBadgeIndex = 0;
const badgeCards = document.querySelectorAll('.badge-card');
const dotsContainer = document.getElementById('dots-container');
const wrapper = document.getElementById('carousel-wrapper');
const slider = document.getElementById('badge-slider');

badgeCards.forEach((_, index) => {
  const dot = document.createElement('div');
  dot.classList.add('dot');
  if (index === 0) dot.classList.add('active');
  dot.addEventListener('click', () => goToBadge(index));
  dotsContainer.appendChild(dot);
});

const dots = document.querySelectorAll('.dot');

function goToBadge(index) {
  currentBadgeIndex = index;

  badgeCards.forEach((card, i) => {
    card.classList.toggle('active', i === currentBadgeIndex);
  });

  dots.forEach((dot, i) => {
    dot.classList.toggle('active', i === currentBadgeIndex);
  });

  const wrapperWidth = wrapper.offsetWidth;
  const targetCard = badgeCards[currentBadgeIndex];
  const cardOffsetLeft = targetCard.offsetLeft;
  const cardWidth = targetCard.offsetWidth;

  const offset = (wrapperWidth / 2) - (cardOffsetLeft + (cardWidth / 2));
  slider.style.transform = `translateX(${offset}px)`;

  document.getElementById('badge-prev-btn').disabled = currentBadgeIndex === 0;
  document.getElementById('badge-next-btn').disabled = currentBadgeIndex === badgeCards.length - 1;
}

function changeBadge(direction) {
  let newIndex = currentBadgeIndex + direction;
  if (newIndex < 0) newIndex = 0;
  if (newIndex >= badgeCards.length) newIndex = badgeCards.length - 1;
  goToBadge(newIndex);
}

// --- 4. PROOF MODAL FUNCTIONS ---
function openProofModal() {
  currentProofImageIndex = 0;
  updateProofModalView();
  document.getElementById('proof-modal').classList.add('active');
}

function updateProofModalView() {
  const current = seminarsData[currentSeminarIndex];
  const modalImg = document.getElementById('modal-img');
  const modalTitle = document.getElementById('modal-title');
  const navControls = document.getElementById('proof-modal-controls');
  const pageIndicator = document.getElementById('proof-page-indicator');

  modalTitle.innerText = `Proof - ${current.title}`;
  modalImg.src = current.proofImgs[currentProofImageIndex];

  if (current.proofImgs.length > 1) {
    navControls.style.display = 'flex';
    pageIndicator.innerText = `${String(currentProofImageIndex + 1).padStart(2, '0')} / ${String(current.proofImgs.length).padStart(2, '0')}`;
    document.getElementById('proof-prev-btn').disabled = currentProofImageIndex === 0;
    document.getElementById('proof-next-btn').disabled = currentProofImageIndex === current.proofImgs.length - 1;
  } else {
    navControls.style.display = 'none';
  }
}

function changeProofImage(direction) {
  const current = seminarsData[currentSeminarIndex];
  const newIndex = currentProofImageIndex + direction;
  if (newIndex >= 0 && newIndex < current.proofImgs.length) {
    currentProofImageIndex = newIndex;
    updateProofModalView();
  }
}

function closeProofModal(event, force = false) {
  if (force || (event && event.target.id === 'proof-modal')) {
    document.getElementById('proof-modal').classList.remove('active');
  }
}

// --- 5. ALL CERTIFICATES SIDEBAR MODAL ---
function openAllCertsModal() {
  const modal = document.getElementById('all-certs-modal');
  const sidebar = document.getElementById('certs-sidebar');
  sidebar.innerHTML = '';

  seminarsData.forEach((item, index) => {
    const thumb = document.createElement('div');
    thumb.className = `cert-thumb-card ${index === currentSeminarIndex ? 'active' : ''}`;
    thumb.onclick = () => loadModalCert(index);

    thumb.innerHTML = `
      <span class="thumb-number">CERTIFICATE ${String(index + 1).padStart(2, '0')}</span>
      <div class="thumb-title">${item.title}</div>
    `;

    sidebar.appendChild(thumb);
  });

  loadModalCert(currentSeminarIndex);
  modal.classList.add('active');
}

function loadModalCert(index) {
  const target = seminarsData[index];
  const mainView = document.getElementById('certs-main-view');

  if (target.certPdf.toLowerCase().endsWith('.jpg') || target.certPdf.toLowerCase().endsWith('.jpeg') || target.certPdf.toLowerCase().endsWith('.png')) {
    mainView.innerHTML = `<img src="${target.certPdf}" alt="${target.title}" style="width:100%; height:100%; object-fit:contain;">`;
  } else {
    const encodedPdfPath = encodeURIComponent(target.certPdf);
    mainView.innerHTML = `<iframe id="modal-pdf-display" class="cert-pdf" src="${encodedPdfPath}#toolbar=0&navpanes=0&scrollbar=1&view=FitH" type="application/pdf"></iframe>`;
  }

  const cards = document.querySelectorAll('.cert-thumb-card');
  cards.forEach((card, idx) => {
    card.classList.toggle('active', idx === index);
  });
}

function closeCertsModal(event, force = false) {
  if (force || (event && event.target.id === 'all-certs-modal')) {
    document.getElementById('all-certs-modal').classList.remove('active');
  }
}

